#include <iostream>
using namespace std;

int main() {
    // Assign whole numbers using the 'int' data type
    int num1 = 3;
    int num2 = 4;
    
    // Calculate the total
    int sum = num1 + num2;

    // Display the result
    std::cout << "Number 1: " << num1 << std::endl;
    std::cout << "Number 2: " << num2 << std::endl;
    std::cout << "The sum is: " << sum << std::endl;

    return 0;
}
